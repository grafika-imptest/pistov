// Drone 360° panoramas (DJI, equirectangular 14400×7200, 13. 10. 2026) → web assets + station data.
//  - assets/pano/<id>-{1024,4096,8192}.webp   (first paint / mobile / desktop)
//  - js/projects/pistov/panoramas.generated.js (GPS, position in plan + aerial view, heading, georeference)
// Georeference of the plan comes from georef.mjs (plan ponds matched to OpenStreetMap water bodies).
// usage: node build-pano.mjs [--skip-images]
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { AERIAL_HOMOGRAPHY } from "../js/projects/pistov/plots.generated.js";

const SRC = "../podklady/panorama";
const OUT = "../assets/pano";
const skipImages = process.argv.includes("--skip-images");
fs.mkdirSync(OUT, { recursive: true });

// heading = compass bearing of the image centre column. Calibrated visually against OpenStreetMap ponds
// (pano-calib-sheet.mjs) and the traced plots (pano-calib-plots.mjs); accuracy ≈ ±2°.
const stations = [
  { id: "stred-30", file: "DJI_0303.JPG", label: "Střed lokality", short: "Střed · 30 m", heading: 133, view: { yaw: 175, pitch: -28 } },
  { id: "stred-60", file: "DJI_0304.JPG", label: "Střed lokality", short: "Střed · 60 m", heading: 126, view: { yaw: 175, pitch: -24 } },
  { id: "vychod", file: "DJI_0305.JPG", label: "Za rybníky", short: "Východ · 60 m", heading: 70, view: { yaw: 242, pitch: -12 } },
  { id: "jih", file: "DJI_0308.JPG", label: "Pole na jihu", short: "Jih · 60 m", heading: 48, view: { yaw: 354, pitch: -14 } },
  { id: "zapad", file: "DJI_0309.JPG", label: "Nad obcí", short: "Západ · 60 m", heading: 95, view: { yaw: 103, pitch: -9 } },
  { id: "sever", file: "DJI_0311.JPG", label: "Nad obcí", short: "Sever · 60 m", heading: 185, view: { yaw: 177, pitch: -11 } },
];

const geo = JSON.parse(fs.readFileSync("../podklady/georef.json", "utf8"));
const { REF, mLat, mLon, T } = geo;
const enu = (lat, lon) => [(lon - REF[1]) * mLon, (lat - REF[0]) * mLat];
const toPlan = ([x, y]) => [T.a * x + T.b * y + T.tx, T.b * x - T.a * y + T.ty];
const applyH = (h, [x, y]) => { const w = h[6] * x + h[7] * y + h[8]; return [(h[0] * x + h[1] * y + h[2]) / w, (h[3] * x + h[4] * y + h[5]) / w]; };
const r1 = (v) => Math.round(v * 10) / 10;

const out = [];
for (const s of stations) {
  const file = path.join(SRC, s.file);
  const xmp = (await sharp(file, { limitInputPixels: false }).metadata()).xmp.toString("utf8");
  const num = (k) => Number((xmp.match(new RegExp(`${k}="([-+\\d.]+)"`)) || [])[1]);
  const lat = num("GpsLatitude"), lon = num("GpsLongitude"), alt = num("RelativeAltitude");
  const m = enu(lat, lon);
  const plan = toPlan(m);
  const date = (xmp.match(/CreateDate="([^"]+)"/) || [])[1];
  if (!skipImages) {
    const base = sharp(file, { limitInputPixels: false });
    for (const [w, q] of [[8192, 70], [4096, 74], [1024, 70]]) {
      await base.clone().resize(w, w / 2).webp({ quality: q, effort: 4 }).toFile(path.join(OUT, `${s.id}-${w}.webp`));
    }
  }
  const sizes = Object.fromEntries([1024, 4096, 8192].map((w) => [w, `assets/pano/${s.id}-${w}.webp`]));
  out.push({
    id: s.id, label: s.label, short: s.short, altitude: r1(alt), lat: +lat.toFixed(7), lon: +lon.toFixed(7), captured: date,
    enu: m.map(r1), plan: plan.map(r1), aerial: applyH(AERIAL_HOMOGRAPHY, plan).map(r1),
    heading: s.heading, view: s.view, sources: sizes, future: null,
  });
  console.log(s.id, "plan", plan.map(Math.round).join(","), "alt", alt);
}
for (const f of fs.readdirSync(OUT)) console.log(f, (fs.statSync(path.join(OUT, f)).size / 1e6).toFixed(2), "MB");

fs.writeFileSync("../js/projects/pistov/panoramas.generated.js", `// GENERATED by tools/build-pano.mjs – do not edit by hand.
// Drone 360° panoramas of the site (DJI Mavic 3 Classic, equirectangular), 13. 10. 2026 – state before construction.
// enu = metres east/north of the reference point; plan/aerial = px in the respective view.
// heading = compass bearing of the centre column of the equirectangular image (calibrated against ponds).
// future: equirectangular image of the same station with the development visualised (to be supplied) → null.
// Plan georeference: plan ponds matched to OpenStreetMap water bodies (© OpenStreetMap contributors, ODbL), residual 2–4 m.
export const PLAN_GEOREF = ${JSON.stringify({ ref: REF, mLat: +mLat.toFixed(4), mLon: +mLon.toFixed(4), a: T.a, b: T.b, tx: T.tx, ty: T.ty })};
export const panoramas = ${JSON.stringify(out, null, 1)};
`);
