// Builds js/projects/pistov/plots.generated.js from the traced site plan.
//  - plan polygon:   traced from catalog p.3 (situační plán M 1:2000), see trace-plots.mjs
//  - aerial polygon: plan polygon projected by the fitted homography (fit-aerial.mjs) – approximate
//  - placement:      centre + axis of the house footprint the architect drew into each plot (PCA of pink pixels)
//  - area + status:  read from the plan (labels; hatched = "rezervované pozemky", legend p.3)
import sharp from "sharp";
import fs from "node:fs";

const traced = JSON.parse(fs.readFileSync("../podklady/plots-traced-final.json", "utf8"));
const { H } = JSON.parse(fs.readFileSync("../podklady/aerial-homography.json", "utf8"));
const { data, info } = await sharp("../podklady/raw/p03_1_3364x3281.png").raw().toBuffer({ resolveWithObject: true });
const W = info.width, C = info.channels;
const px = (x, y) => { const i = (y * W + x) * C; return [data[i], data[i + 1], data[i + 2]]; };
const apply = (h, [x, y]) => { const w = h[6] * x + h[7] * y + h[8]; return [(h[0] * x + h[1] * y + h[2]) / w, (h[3] * x + h[4] * y + h[5]) / w]; };
const inPoly = (x, y, P) => { let c = false; for (let i = 0, j = P.length - 1; i < P.length; j = i++) { const [xi, yi] = P[i], [xj, yj] = P[j]; if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c; } return c; };
const r1 = (v) => Math.round(v * 10) / 10;

const AREA = {1:696,2:598,3:578,4:583,5:576,6:635,7:661,8:660,9:621,10:607,11:601,12:600,13:1067,14:903,15:953,16:927,17:787,18:633,19:556,20:587,21:584,22:568,23:601,24:600,25:600,26:600,27:599,28:570,29:598,30:626,31:602,32:604,33:605,34:606,35:607,36:710,37:580,38:571,39:557,40:538,41:499,42:524,43:542,44:573,45:579,46:601,47:614,48:614,49:612,50:599,51:597,52:592,53:562,54:615,55:570,56:570,57:571,58:585,60:682,61:659,62:586,63:605,64:917,65:938,66:840,67:1423,68:1221,69:674,70:900,71:603,72:651,73:697};
const RESERVED = new Set([64, 65, 66, 67, 68, 69, 70, 71, 72]);
// label positions of the reserved block 64–70 (no individual boundaries legible in the raster)
const S = 3364 / 1600;
const LABEL_64_70 = { 64: [237, 688], 65: [281, 712], 66: [300, 773], 67: [334, 655], 68: [392, 630], 69: [472, 618], 70: [544, 560] };
const BLOCK_64_70 = [[320,1436],[567,1205],[602,1191],[700,1145],[800,1099],[951,1000],[1028,1104],[1197,999],[1280,1149],[600,1678]];

function placement(poly) {
  const xs = poly.map((p) => p[0]), ys = poly.map((p) => p[1]);
  const all = [], light = [];
  for (let y = Math.min(...ys); y <= Math.max(...ys); y++) for (let x = Math.min(...xs); x <= Math.max(...xs); x++) {
    if (!inPoly(x, y, poly)) continue; const [r, g, b] = px(x, y);
    if (r > 215 && r - g > 25 && r - b > 20 && g > 120) { all.push([x, y]); if (g > 200) light.push([x, y]); }
  }
  if (all.length < 200) return null;
  const mean = (a) => [a.reduce((s, p) => s + p[0], 0) / a.length, a.reduce((s, p) => s + p[1], 0) / a.length];
  const [cx, cy] = mean(all);
  let sxx = 0, syy = 0, sxy = 0; for (const [x, y] of all) { sxx += (x - cx) ** 2; syy += (y - cy) ** 2; sxy += (x - cx) * (y - cy); }
  const angle = 0.5 * Math.atan2(2 * sxy, sxx - syy); // main axis, radians, plan px space
  return { c: [r1(cx), r1(cy)], angle: Math.round(angle * 1000) / 1000, wing: light.length > 100 ? mean(light).map(r1) : null };
}

const plots = [];
for (const t of traced) {
  const no = t.no;
  const base = { id: `P${String(no).padStart(2, "0")}`, no, area: AREA[no], status: RESERVED.has(no) ? "reserved" : "available" };
  if (no >= 64 && no <= 70) {
    const l = LABEL_64_70[no].map((v) => v * S);
    plots.push({ ...base, geometry: null, label: { plan: l.map(r1), aerial: apply(H, l).map(r1) }, placement: null, geometryNote: "Hranice jednotlivých parcel v rezervovaném bloku 64–70 nejsou v rastru plánu čitelné." });
    continue;
  }
  const plan = t.poly.map(([x, y]) => [x, y]);
  const aerial = plan.map((p) => apply(H, p).map(r1));
  const c = [plan.reduce((s, p) => s + p[0], 0) / plan.length, plan.reduce((s, p) => s + p[1], 0) / plan.length];
  plots.push({
    ...base,
    geometry: { plan, aerial, method: t.method, approx: t.method !== "flood" },
    label: { plan: c.map(r1), aerial: apply(H, c).map(r1) },
    placement: placement(plan),
  });
}
plots.sort((a, b) => a.no - b.no);
const reservedBlock = { ids: [64, 65, 66, 67, 68, 69, 70].map((n) => `P${n}`), plan: BLOCK_64_70, aerial: BLOCK_64_70.map((p) => apply(H, p).map(r1)) };

const header = `// GENERATED by tools/build-data.mjs – do not edit by hand.
// Source: Pístov – katalog rodinných domů, TAM architekti, duben 2026, str. 3 (situační plán M 1:2000).
// Coordinates: plan = px of assets/img/plan-3364.webp (3364×3281), aerial = px of assets/img/aerial-3400.webp (3419×2038 source).
// status: "reserved" = šrafované v plánu (legenda „rezervované pozemky“), "available" = „pozemky k prodeji“. Stav k dubnu 2026.
`;
fs.writeFileSync("../js/projects/pistov/plots.generated.js", `${header}export const PLAN_SIZE = [3364, 3281];
export const AERIAL_SIZE = [3419, 2038];
export const PLAN_M_PER_PX = 0.1693; // 284.7 mm print width × 2000 / 3364 px
export const AERIAL_HOMOGRAPHY = ${JSON.stringify(H.map((v) => +v.toPrecision(10)))};
export const reservedBlock = ${JSON.stringify(reservedBlock)};
export const plotsSource = ${JSON.stringify(plots)};
`);
console.log(plots.length, "plots;", plots.filter((p) => p.placement).length, "with placement");

// hero overlay: the plan, cut out to the development area with a feathered edge
const hull = (points) => { const p = points.slice().sort((a, b) => a[0] - b[0] || a[1] - b[1]); const cr = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]); const lo = [], up = [];
  for (const q of p) { while (lo.length >= 2 && cr(lo.at(-2), lo.at(-1), q) <= 0) lo.pop(); lo.push(q); }
  for (const q of p.reverse()) { while (up.length >= 2 && cr(up.at(-2), up.at(-1), q) <= 0) up.pop(); up.push(q); } return lo.slice(0, -1).concat(up.slice(0, -1)); };
const env = hull(plots.flatMap((p) => p.geometry ? p.geometry.plan : []).concat(BLOCK_64_70));
const mask = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="3364" height="3281"><defs><filter id="f"><feGaussianBlur stdDeviation="45"/></filter></defs><polygon points="${env.map((p) => p.join(",")).join(" ")}" fill="#fff" stroke="#fff" stroke-width="160" stroke-linejoin="round" filter="url(#f)"/></svg>`);
const alpha = await sharp(mask).resize(1682).greyscale().raw().toBuffer();
const planSmall = await sharp("../podklady/raw/p03_1_3364x3281.png").resize(1682).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const rgba = Buffer.alloc(1682 * planSmall.info.height * 4);
for (let i = 0; i < 1682 * planSmall.info.height; i++) { rgba[i * 4] = planSmall.data[i * 3]; rgba[i * 4 + 1] = planSmall.data[i * 3 + 1]; rgba[i * 4 + 2] = planSmall.data[i * 3 + 2]; rgba[i * 4 + 3] = alpha[i]; }
await sharp(rgba, { raw: { width: 1682, height: planSmall.info.height, channels: 4 } }).webp({ quality: 80, alphaQuality: 70 }).toFile("../assets/img/plan-cutout-1682.webp");
console.log("plan cutout written");
